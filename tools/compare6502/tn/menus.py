#!/usr/bin/env python3
"""Keep TN raw-menu length/text/self-pointer/key/$9A/terminator layout."""
import argparse
from pathlib import Path
import re
from literals import ROOT,decode

def generate(text):
    header=['/* Generated by tools/compare6502/tn/menus.py. */','#ifndef TN_MENUS_H','#define TN_MENUS_H','#include "tn_types.h"']
    code=['/* Exact raw Action! menu entries, including self relocations. */','#include "tn_menus.h"']
    for match in re.finditer(r'^PROC\s+(\w+)=\*\(\)\s*\n\[([^]]+)\]',text.replace('\r\n','\n'),re.M):
        name,body=match.groups();entries=list(re.finditer(r'"([^"\n]*)"\s*\'(.)',body))
        residue=body
        for entry in reversed(entries):residue=residue[:entry.start()]+residue[entry.end():]
        assert residue.strip()=='$00',(name,residue)
        header.append(f'typedef struct Menu_{name} {{')
        values=[];size=1
        for i,entry in enumerate(entries):
            value=decode(entry[1]);n=len(value);size+=n+5
            header.append(f'    struct {{ u8 n,text[{n}];void *self;u8 key,token; }} e{i};')
            values.append('{'+str(n)+',{'+','.join(f'0x{b:02X}' for b in value)+'},'+f'(void*)&tn_menu_{name}.e{i},0x{ord(entry[2]):02X},0x9A'+'}')
        header+=['    u8 stop;',f'}} Menu_{name};',f'TN_ASSERT(menu_{name}_size,sizeof(Menu_{name})=={size});',f'extern Menu_{name} tn_menu_{name};',f'#define menu_{name} ((Bytes)&tn_menu_{name})']
        code.append(f'Menu_{name} tn_menu_{name} = '+'{'+','.join(values)+',0};')
    header+=['#pragma compile("tn_menus.c")','#endif']
    return {'samples/tn/c/tn_menus.h':'\n'.join(header)+'\n','samples/tn/c/tn_menus.c':'\n'.join(code)+'\n'}

def main():
    p=argparse.ArgumentParser(description=__doc__);p.add_argument('--check',action='store_true');args=p.parse_args()
    text=(ROOT/'samples/tn/modern/TN.ACT').read_text();result=generate(text)
    assert result==generate(text.replace('\r\n','\n').replace('\n','\r\n'))
    for name,text in result.items():
        if args.check:assert (ROOT/name).read_text().replace('\r\n','\n')==text,name
        else:(ROOT/name).write_text(text)
    print('TN menu data checked' if args.check else 'TN menu data generated')
if __name__=='__main__':main()
