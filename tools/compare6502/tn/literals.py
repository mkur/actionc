#!/usr/bin/env python3
"""Extract TN's supported counted-byte literals without C character encoding."""
import argparse
import hashlib
import json
from pathlib import Path
import re
ROOT=Path(__file__).resolve().parents[3]

def decode(text):
    result=bytearray();i=0
    while i<len(text):
        if text.startswith('\\{',i):
            end=text.index('}',i+2);body=text[i+2:end]
            if re.fullmatch(r'\$[0-9A-Fa-f]{2}',body): result.append(int(body[1:],16))
            elif body.startswith('INV:'):result.extend(b|128 for b in decode(body[4:]))
            else:raise ValueError(f'unsupported TN literal escape {body!r}')
            i=end+1
        else:
            b=ord(text[i]);assert b<128,(text,i);result.append(b);i+=1
    return bytes(result)

def strings(text):
    # Action! comments start at an unquoted semicolon. Checked sources use
    # single-line strings; unsupported unterminated strings are rejected.
    for number,line in enumerate(text.replace('\r\n','\n').splitlines(),1):
        i=0
        while i<len(line):
            if line[i]==';':break
            if line[i]=='"':
                end=line.index('"',i+1);yield number,line[i+1:end];i=end+1
            else:i+=1

def generate(inputs):
    values={};names={};references=[]
    for source,text in inputs:
        for line,raw in strings(text):
            value=decode(raw)
            if value not in values:
                slug=re.sub('[^a-z0-9]+','_', ''.join(chr(b&127) for b in value).lower()).strip('_')[:44] or 'bytes'
                name='text_'+slug
                if name in names:name+='_'+hashlib.sha256(value).hexdigest()[:8]
                names[name]=value;values[value]=name
            references.append(dict(source=source,line=line,text=raw,symbol=values[value]))
    header=['/* Generated by tools/compare6502/tn/literals.py. */','#ifndef TN_TEXT_H','#define TN_TEXT_H','#include "tn_types.h"']
    code=['/* Generated counted ATASCII data; no C/PETSCII literal conversion. */','#include "tn_text.h"']
    for name,value in names.items():
        assert len(value)<=255
        header.append(f'extern u8 {name}[{len(value)+1}];')
        code.append('u8 '+name+'[] = {'+','.join(f'0x{b:02X}' for b in bytes([len(value)])+value)+'};')
    header+=['#pragma compile("tn_text.c")','#endif']
    return {'samples/tn/c/tn_text.h':'\n'.join(header)+'\n','samples/tn/c/tn_text.c':'\n'.join(code)+'\n','surveys/tn/c-oscar64/literals.json':json.dumps(references,indent=2)+'\n'}

def main():
    parser=argparse.ArgumentParser(description=__doc__);parser.add_argument('--check',action='store_true');args=parser.parse_args()
    inputs=[(f'samples/tn/modern/{name}',(ROOT/f'samples/tn/modern/{name}').read_text()) for name in ['LIB.ACT','TN.ACT','TNDBG.ACT']]
    result=generate(inputs)
    assert result==generate([(n,s.replace('\r\n','\n').replace('\n','\r\n')) for n,s in inputs]), 'LF/CRLF generator path differs'
    for name,text in result.items():
        path=ROOT/name
        if args.check:assert path.read_text().replace('\r\n','\n')==text,name
        else:path.write_text(text)
    print('TN literal generation checked' if args.check else 'TN literal data generated')
if __name__=='__main__':main()
